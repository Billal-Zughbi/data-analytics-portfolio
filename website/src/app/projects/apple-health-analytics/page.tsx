import type { Metadata } from "next";
import LineChart from "@/components/LineChart";
import summary from "@/data/apple-health-summary.json";
import { profile } from "@/data/profile";

export const metadata: Metadata = {
  title: `Apple Health Analytics | ${profile.name}`,
  description: "Python pipeline and Power BI model for privacy-safe Apple Health analytics.",
};

const fmt = (v: number | null, digits = 0) =>
  v === null ? "–" : v.toLocaleString("en-US", { maximumFractionDigits: digits, minimumFractionDigits: digits });

export default function AppleHealthCaseStudy() {
  const synthetic = summary.dataSource === "synthetic";
  const k = summary.kpis;

  return (
    <article className="case">
      <header className="hero container">
        <p className="eyebrow">Case study · Python · Power BI</p>
        <h1>Apple Health Analytics Dashboard</h1>
        <p className="lead">
          A pipeline that streams an Apple Health XML export, normalizes 40 metrics across devices and years, and
          publishes a privacy-safe star schema for Power BI analysis of cardiovascular, activity, mobility and
          environmental trends.
        </p>
        {synthetic && (
          <p className="notice">
            Charts on this page use <strong>synthetic data</strong> generated by the pipeline&apos;s demo mode. Personal
            health records are never published; the real dashboard runs on locally sanitized aggregates.
          </p>
        )}
        <div className="actions">
          <a className="btn primary" href={`${profile.repo}/tree/main/projects/apple-health-analytics`}>
            View the code
          </a>
        </div>
      </header>

      <section aria-labelledby="kpis">
        <div className="container">
          <h2 id="kpis">Results {synthetic ? "(demo data)" : ""}</h2>
          <div className="stats">
            <div className="tile">
              <div className="value">{fmt(summary.recordsProcessed)}</div>
              <div className="label">records processed</div>
            </div>
            <div className="tile">
              <div className="value">{fmt(k.avgDailySteps)}</div>
              <div className="label">average daily steps</div>
            </div>
            <div className="tile">
              <div className="value">{fmt(k.avgRestingHeartRate, 1)}</div>
              <div className="label">average resting heart rate (bpm)</div>
            </div>
            <div className="tile">
              <div className="value">{fmt(k.avgHrvSdnn, 1)}</div>
              <div className="label">average HRV, SDNN (ms)</div>
            </div>
          </div>
        </div>
      </section>

      <section aria-labelledby="trends">
        <div className="container">
          <h2 id="trends">Trends</h2>
          <LineChart
            title="Average daily steps"
            subtitle={`Monthly mean of daily totals, ${summary.firstMonth} to ${summary.lastMonth}`}
            unit="steps"
            data={summary.monthly.steps}
          />
          <LineChart
            title="Resting heart rate"
            subtitle="Monthly mean of daily resting heart rate"
            unit="bpm"
            data={summary.monthly.restingHeartRate}
            digits={1}
          />
        </div>
      </section>

      <section aria-labelledby="how">
        <div className="container">
          <h2 id="how">How it works</h2>
          <pre className="flow">{`export.xml ─► stream parse ─► normalize units ─► daily aggregates ─► star schema ─► Power BI
 (local only)  ElementTree     km · kg · % · °C     date × metric      CSV tables      DAX measures`}</pre>
          <ul>
            <li>
              <strong>Streaming extraction.</strong> <code>iterparse</code> reads exports of 1 GB+ in constant memory and
              keeps only type, date, value and unit.
            </li>
            <li>
              <strong>Normalization.</strong> Units recorded by different devices (miles vs km, lb vs kg, fractions vs
              percentages) are converted to one canonical unit per metric.
            </li>
            <li>
              <strong>Star schema.</strong> A daily fact table joins to metric and date dimensions, ready for
              time-intelligence DAX: rolling averages, year-over-year change and goal attainment.
            </li>
          </ul>
        </div>
      </section>

      <section aria-labelledby="privacy">
        <div className="container">
          <h2 id="privacy">Privacy by design</h2>
          <ul>
            <li>Raw exports never leave the local machine and are blocked by the repository&apos;s .gitignore.</li>
            <li>Device names, app sources, timestamps, time zones and metadata are dropped at parse time.</li>
            <li>Only an allowlist of 40 metrics is kept; reproductive, clinical and medication data are excluded.</li>
            <li>An output guard and automated tests fail the build if an identifying field ever reaches a published file.</li>
          </ul>
        </div>
      </section>
    </article>
  );
}
